CREATE TABLE "User" (
 id TEXT PRIMARY KEY,name TEXT NOT NULL,email TEXT NOT NULL UNIQUE,"passwordHash" TEXT NOT NULL,
 role TEXT NOT NULL DEFAULT 'AGENT',active BOOLEAN NOT NULL DEFAULT true,
 "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,"lastSeenAt" TIMESTAMPTZ(3)
);
CREATE TABLE "Session" (
 id TEXT PRIMARY KEY,"userId" TEXT NOT NULL REFERENCES "User"(id) ON DELETE CASCADE ON UPDATE CASCADE,
 "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,"expiresAt" TIMESTAMPTZ(3) NOT NULL
);
CREATE INDEX "Session_expiresAt_idx" ON "Session"("expiresAt");
ALTER TABLE "Lead" ADD COLUMN "assignedToId" TEXT REFERENCES "User"(id) ON UPDATE CASCADE;
CREATE INDEX "Lead_assignedToId_idx" ON "Lead"("assignedToId");
ALTER TABLE "AuditLog" ADD COLUMN "userId" TEXT REFERENCES "User"(id) ON UPDATE CASCADE ON DELETE SET NULL;
CREATE TABLE "Note" (
 id TEXT PRIMARY KEY,"leadId" TEXT NOT NULL REFERENCES "Lead"(id) ON UPDATE CASCADE,
 "userId" TEXT NOT NULL REFERENCES "User"(id) ON UPDATE CASCADE,body TEXT NOT NULL,
 "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "Note_leadId_createdAt_idx" ON "Note"("leadId","createdAt");
CREATE TABLE "LoginAttempt" (id TEXT PRIMARY KEY,key TEXT NOT NULL,"createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX "LoginAttempt_key_createdAt_idx" ON "LoginAttempt"(key,"createdAt");
